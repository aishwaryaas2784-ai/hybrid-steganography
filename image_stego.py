"""
image_stego.py
Chaotic-map (logistic map) based LSB image steganography.
Pixel embedding order is generated by a logistic map chaotic sequence,
seeded deterministically from the password -- same password always
produces the same order, on any machine, with no shared order file needed.
"""

import hashlib
from PIL import Image

DELIMITER = "1111111111111110"


def message_to_binary(message: str) -> str:
    return ''.join(format(ord(char), '08b') for char in message)


def binary_to_message(binary: str) -> str:
    chars = [binary[i:i+8] for i in range(0, len(binary), 8)]
    return ''.join(chr(int(c, 2)) for c in chars if len(c) == 8)


def get_embedding_order(width: int, height: int, password: str):
    """
    Generates pixel embedding order using a logistic map chaotic sequence:
        x_(n+1) = r * x_n * (1 - x_n)
    The map is seeded from the password's SHA-256 hash, so it's fully
    reproducible with the correct password but practically impossible to
    guess without it (chaotic sequences are extremely sensitive to the
    starting value -- a one-character password change produces a
    completely different pixel order).
    """
    seed_int = int(hashlib.sha256(password.encode("utf-8")).hexdigest(), 16)

    # Initial condition x0, kept strictly inside (0, 1)
    x = (seed_int % 999999 + 1) / 1000000.0
    r = 3.99  # chaotic regime constant (must be close to 4 for full chaos)

    total_pixels = width * height
    chaotic_values = []
    for _ in range(total_pixels):
        x = r * x * (1 - x)
        chaotic_values.append(x)

    coords = [(y, xc) for y in range(height) for xc in range(width)]

    # Sort coordinates by their paired chaotic value -> chaotic permutation
    paired = list(zip(chaotic_values, coords))
    paired.sort(key=lambda p: p[0])
    return [coord for _, coord in paired]


def encode_image(cover_path: str, secret_message: str, output_path: str, password: str):
    img = Image.open(cover_path).convert("RGB")
    pixels = img.load()

    binary_message = message_to_binary(secret_message) + DELIMITER
    total_bits = len(binary_message)

    max_capacity = img.width * img.height * 3
    if total_bits > max_capacity:
        raise ValueError(
            f"Message too large for this image. Capacity: {max_capacity} bits, needed: {total_bits} bits."
        )

    embedding_order = get_embedding_order(img.width, img.height, password)

    bit_index = 0
    for (y, x) in embedding_order:
        if bit_index >= total_bits:
            break
        pixel = list(pixels[x, y])
        for channel in range(3):
            if bit_index < total_bits:
                pixel[channel] = (pixel[channel] & ~1) | int(binary_message[bit_index])
                bit_index += 1
        pixels[x, y] = tuple(pixel)

    img.save(output_path)
    print(f"✅ Image encoding complete (chaotic-map order). Bits embedded: {total_bits}")
    return output_path


def decode_image(stego_path: str, password: str) -> str:
    img = Image.open(stego_path).convert("RGB")
    pixels = img.load()

    embedding_order = get_embedding_order(img.width, img.height, password)

    binary_data = ""
    for (y, x) in embedding_order:
        pixel = pixels[x, y]
        for channel in range(3):
            binary_data += str(pixel[channel] & 1)
            if binary_data.endswith(DELIMITER):
                binary_data = binary_data[:-len(DELIMITER)]
                return binary_to_message(binary_data)

    return binary_to_message(binary_data)


